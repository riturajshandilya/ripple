// Regenerate added intents and backend mappings while preserving their stable names.
const fs = require('node:fs');
const carriers = JSON.parse(fs.readFileSync('skill/additional-carriers.json', 'utf8'));
const file = 'skill/en-US.json';
const model = JSON.parse(fs.readFileSync(file, 'utf8'));
const intents = model.interactionModel.languageModel.intents;
const existing = intents.filter((i) => !/^Expanded[A-Z]+Intent$/.test(i.name));
const sampleSet = new Set(existing.flatMap((i) => i.samples));
const names = new Set(existing.map((i) => i.name));
const mapping = {};
if (!Array.isArray(carriers)) throw Error('Invalid carrier list');
for (const entry of carriers) {
  const { name, phrase } = entry;
  if (typeof name !== 'string' || !/^Expanded[A-Z]+Intent$/.test(name) || names.has(name))
    throw Error('Invalid or duplicate intent name');
  if (typeof phrase !== 'string' || !/^[a-z]+(?: [a-z]+)*$/.test(phrase))
    throw Error('Invalid carrier');
  const sample = `${phrase} {question}`;
  if (sampleSet.has(sample)) throw Error('Duplicate carrier');
  sampleSet.add(sample);
  names.add(name);
  mapping[name] = phrase;
  existing.push({
    name,
    slots: [{ name: 'question', type: 'AMAZON.SearchQuery' }],
    samples: [sample],
  });
}
const slots = existing.reduce((total, intent) => total + (intent.slots?.length ?? 0), 0);
if (existing.length > 250 || existing.length + slots >= 350)
  throw Error('Model exceeds conservative intent and slot budget');
model.interactionModel.languageModel.intents = existing;
fs.writeFileSync(file, JSON.stringify(model, null, 2) + '\n');
fs.writeFileSync(
  'src/alexa/generated-carriers.ts',
  `// Generated by scripts/generate-carriers.cjs; edit skill/additional-carriers.json instead.\nexport const generatedCarriers: Record<string, string> = ${JSON.stringify(mapping, null, 2)};\n`,
);
console.log(
  `Generated ${carriers.length} carrier intents; ${existing.length} intents and ${slots} slot declarations.`,
);
